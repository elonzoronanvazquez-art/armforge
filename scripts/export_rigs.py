"""Write src/shared/Config/CreatureRigs.luau from docs/generated_assets.json (the segmented meshes made by scripts/gen_rigs.py).
Every id in the generated file came from the Studio tool; nothing is typed by hand.

Usage: python scripts/export_rigs.py
"""
import json
import os

ROOT = os.path.join(os.path.dirname(__file__), "..")
STATE = os.path.join(ROOT, "docs", "generated_assets.json")
OUT = os.path.join(ROOT, "src", "shared", "Config", "CreatureRigs.luau")


def asset(value):
    return value if value.startswith("rbxassetid://") else "rbxassetid://" + value


def fmt(n):
    return ("%.4f" % n).rstrip("0").rstrip(".") if abs(n) > 1e-6 else "0"


def main():
    state = json.load(open(STATE, encoding="utf-8"))
    lines = [
        "--!strict",
        "-- GENERATED by scripts/export_rigs.py from docs/generated_assets.json: segmented AI creature meshes (Studio generate_mesh).",
        "-- Each part keeps the CFrame it was generated at, relative to the model's bounding-box centre, so the builder reassembles the",
        "-- creature as generated and then rigs the pieces (server/World/CreatureBuilder). Do not edit by hand; regenerate instead.",
        "",
        "local CreatureRigs = {}",
        "",
        "export type Part = { name: string, mesh: string, texture: string, size: Vector3, cf: CFrame }",
        "export type Rig = { bbox: Vector3, parts: { Part } }",
        "",
        "CreatureRigs.Defs = {",
    ]
    for name in sorted(k for k, v in state.items() if k.startswith("Rig") and v.get("status") == "Completed"):
        entry = state[name]
        b = entry["bbox"]
        lines.append("\t%s = {" % name)
        lines.append("\t\tbbox = Vector3.new(%s, %s, %s)," % (fmt(b[0]), fmt(b[1]), fmt(b[2])))
        lines.append("\t\tparts = {")
        for p in entry["parts"]:
            role = p["name"].replace("_geom", "")
            s = p["size"]
            cf = ", ".join(fmt(c) for c in p["cf"])
            lines.append(
                '\t\t\t{ name = "%s", mesh = "%s", texture = "%s", size = Vector3.new(%s, %s, %s), cf = CFrame.new(%s) },'
                % (role, asset(p["mesh"].replace("rbxassetid://", "")), asset(p["tex"].replace("rbxassetid://", "")) if p["tex"] else "", fmt(s[0]), fmt(s[1]), fmt(s[2]), cf)
            )
        lines.append("\t\t},")
        lines.append("\t},")
    lines += ["} :: { [string]: Rig }", "", "return CreatureRigs", ""]
    open(OUT, "w", encoding="utf-8", newline="\n").write("\n".join(lines))
    print("wrote", OUT)


if __name__ == "__main__":
    main()
